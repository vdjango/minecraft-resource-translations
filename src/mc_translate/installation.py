"""Persistent first-install wizard; existing administrators retain their setup."""
import asyncio
import json
import time
from pathlib import Path

from aiohttp import web

from .admin_account import write_private
from .mirror import read_settings, settings_path, validate_settings
from .mirror_catalog import write_json


class Installation:
    sections = ('site', 'translation', 'resources', 'mail')

    def __init__(self, api, control, pages):
        self.api, self.control, self.pages = api, control, pages
        self.path = Path(api.config.database).resolve().parent / 'installation.json'
        if self.path.exists():
            self.state = json.loads(self.path.read_text(encoding='utf-8'))
        else:
            existing = api.admin_accounts.initialized or bool(api.config.admin_token)
            self.state = dict(complete=existing, sections=[])
            self.save()
        self.lock = asyncio.Lock()

    @property
    def required(self):
        return not self.state['complete']

    def save(self):
        write_private(self.path, json.dumps(self.state))

    def authorized(self, request):
        try:
            self.api.require_admin(request)
            return True
        except Exception as exc:
            from .api import ApiError
            if isinstance(exc, ApiError):
                return False
            raise

    def check_origin(self, request):
        origin = request.headers.get('Origin')
        if origin and origin not in (self.api.config.public_url.rstrip('/'), request.scheme+'://'+request.host):
            raise ValueError('invalid_origin')

    async def status(self, request):
        authenticated = self.authorized(request)
        data = dict(required=self.required, initialized=self.api.admin_accounts.initialized,
                    authenticated=authenticated, sections=self.state['sections'])
        if self.required and authenticated:
            resources = {key:value for key,value in read_settings(self.api.config,effective=False).items() if key!='sources'}
            data.update(settings=self.api.settings.public(), resources=resources,
                        cache_root=str(Path(self.api.config.mirror_root).resolve()))
        return web.json_response(data)

    async def account(self, request):
        from .api import ApiError
        self.check_origin(request)
        self.api.rate(request, 'installation_account', 8, 300)
        data = await request.json()
        if not isinstance(data, dict):
            raise ApiError('invalid_credentials', 400)
        async with self.api.admin_login_lock:
            if not self.required or self.api.admin_accounts.initialized:
                raise ApiError('setup_already_initialized', 409)
            # First installation is claimed through the browser. Recovery of an
            # existing owner still requires the private one-use recovery link.
            token = self.api.admin_accounts.prepare_setup().split('#', 1)[1]
            try:
                await asyncio.to_thread(self.api.admin_accounts.complete, token, data.get('username'),
                                        data.get('password'), data.get('password_confirm'))
            except ValueError:
                raise ApiError('invalid_credentials', 400)
            self.api.admin_sessions.clear()
        return self.api.admin_cookie()

    async def configure(self, request):
        from .api import ApiError
        self.api.require_admin(request)
        self.check_origin(request)
        data = await request.json()
        if not isinstance(data, dict) or data.get('section') not in self.sections or not isinstance(data.get('settings'), dict):
            raise ApiError('invalid_settings', 400)
        section, changes = data['section'], data['settings']
        allowed = dict(site={'public_url'},
                       translation={'base_url','api_key','model','reasoning_effort','daily_token_limit',
                                    'monthly_token_limit','daily_call_limit','max_completion_tokens','model_timeout'},
                       mail={'mail_enabled','smtp_host','smtp_port','smtp_security','smtp_username',
                             'smtp_password','mail_from','mail_to','mail_timeout'})
        async with self.lock:
            if not self.required:
                raise ApiError('setup_already_completed', 409)
            if section == 'resources':
                previous = read_settings(self.api.config, effective=False)
                # Automatic mappings are generated by the resource process;
                # they never become manually persisted wizard settings.
                changes = {key:value for key,value in changes.items() if key!='sources'}
                if isinstance(changes.get('policies'), dict):
                    changes['policies'] = {**previous['policies'], **changes['policies']}
                values = validate_settings({**previous, **changes})
                await asyncio.to_thread(write_json, settings_path(self.api.config), values)
                try:
                    await self.control.call(dict(action='trim'))
                except ValueError:
                    await asyncio.to_thread(write_json, settings_path(self.api.config), previous)
                    raise
            else:
                if set(changes) - allowed[section] or not changes:
                    raise ApiError('invalid_settings', 400)
                self.api.settings.apply(changes)
                if section == 'site':
                    self.api.admin_accounts.origin = self.api.config.public_url.rstrip('/')
                    if self.api.config.federation_role == 'hub':
                        self.api.app['federation'].hub = self.api.config.public_url.rstrip('/')
                        self.pages.base = self.api.config.public_url.rstrip('/')
                        self.pages.cache.clear()
                        self.pages.cache_bytes = 0
                if section == 'translation':
                    self.api.engine.wake.set()
            if section not in self.state['sections']:
                self.state['sections'].append(section)
            self.save()
        return await self.status(request)

    async def finish(self, request):
        from .api import ApiError
        self.api.require_admin(request)
        self.check_origin(request)
        async with self.lock:
            if not self.required:
                return web.json_response(dict(complete=True))
            if not self.api.admin_accounts.initialized or set(self.sections)-set(self.state['sections']):
                raise ApiError('setup_incomplete', 400)
            self.state.update(complete=True, completed_at=int(time.time()))
            self.save()
        return self.api.admin_cookie()

    async def page(self, request):
        if not self.required:
            return web.Response(status=302, headers={'Location':'/admin', 'Cache-Control':'no-store'})
        return self.pages.response(request, (self.pages.root/'setup.html').read_text(encoding='utf-8'))

    def gate(self, request):
        """Redirect browser entry points; never replace API JSON with HTML."""
        if not self.required:
            return None
        path = request.path
        if path in ('/setup', '/health') or path.startswith('/v1/setup/'):
            return None
        if path.startswith('/assets/') and not path.endswith('.html'):
            return None
        if path.startswith('/v1/') or path in ('/mirror-api/status', '/openapi.json', '/hash-vectors.json'):
            # The owner can configure through the wizard or its existing admin APIs.
            if path == '/v1/admin/session' or path.startswith('/v1/admin/') and self.authorized(request):
                return None
            return web.json_response(dict(code='setup_required', setup_url='/setup'), status=503,
                                     headers={'Cache-Control':'no-store'})
        if request.method in ('GET','HEAD'):
            return web.Response(status=302, headers={'Location':'/setup','Cache-Control':'no-store',
                                                     'X-Robots-Tag':'noindex, nofollow'})
        return None
